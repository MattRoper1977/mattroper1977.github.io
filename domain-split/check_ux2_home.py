def render_home(record_path, lessons_root):
    """The homepage as the builder renders it, with the audience record and Lessons root given."""
    preview_file = HERE / 'preview.html'  # generated by CI; the home branch does not read it
    preview = preview_file.read_text() if preview_file.is_file() else ''
    config = json.loads((HERE / 'config.json').read_text())
    saved = (bp.AUDIENCE_RECORD, bp.LESSONS_ROOT, home_slots.RECORD)
    bp.AUDIENCE_RECORD, bp.LESSONS_ROOT = record_path, (Path(lessons_root) if lessons_root else None)
    # J93: home_slots reads the record by key at <site root>/RECORD; an absolute path plants it.
    home_slots.RECORD = str(Path(record_path).resolve())
    try:
        return bp.render_page(preview, 'home', config['education_origin'], config)
    finally:
        bp.AUDIENCE_RECORD, bp.LESSONS_ROOT, home_slots.RECORD = saved


class HomePage(HTMLParser):
    """The J93 homepage as the parser sees it: slots, door cards, tiles, flagship cards, tool cards."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.slots, self.doors, self.tiles, self.tools, self.cards = {}, [], [], [], []
        self.h1 = 0
        self._open = []  # (tag, capture keys)

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        cls = (a.get('class') or '').split()
        if tag == 'h1':
            self.h1 += 1
        if tag == 'a' and 'home-door-card' in cls:
            self.doors.append(a.get('href'))
        if tag == 'a' and 'home-subject-tile' in cls:
            self.tiles.append(a.get('href'))
        if tag == 'a' and 'home-tool-card' in cls:
            self.tools.append(a.get('href'))
        if tag == 'article' and a.get('data-pathway-card') is not None:
            self.cards.append({'key': a.get('data-pathway-card'), 'lesson': None, 'badges': 0, 'byline': ''})
        if tag == 'a' and (a.get('data-slot-attr') or '').endswith('.lessonPath') and self.cards:
            self.cards[-1]['lesson'] = a.get('href')
        if tag == 'li' and 'home-pack-badge' in cls and self.cards:
            self.cards[-1]['badges'] += 1
        keys = []
        if a.get('data-slot'):
            keys.append(a['data-slot'] + ('#' + a['data-derive'] if a.get('data-derive') else ''))
        for c in ('home-pathway-byline', 'home-door-byline'):
            if c in cls:
                keys.append('.' + c)
        if tag in VOID:
            return
        self._open.append((tag, keys))
        for k in keys:
            self.slots.setdefault(k, []).append('')

    def handle_endtag(self, tag):
        for i in range(len(self._open) - 1, -1, -1):
            if self._open[i][0] == tag:
                del self._open[i:]
                return

    def handle_data(self, data):
        for _, keys in self._open:
            for k in keys:
                self.slots[k][-1] += data
                if k == '.home-pathway-byline' and self.cards:
                    self.cards[-1]['byline'] += data

    def slot(self, key):
        values = self.slots.get(key, [])
        return ' '.join(values[0].split()) if values else None


def parse_home(page):
    p = HomePage()
    p.feed(page)
    for i, card in enumerate(p.cards):
        card.update({f: p.slot(f'flagship.{i}.{f}') for f in ('pathway', 'week', 'title', 'outcome')})
        card['byline'] = ' '.join(card['byline'].split())
        card['members'] = [(p.slot(f'flagship.{i}.packMembers.{k}.path#ext'), p.slot(f'flagship.{i}.packMembers.{k}.path#label'))
                           for k in range(card['badges'] - 1)]
    p.door_labels = [p.slot(f'audiences.doors.{i}.label') for i in range(len(p.doors))]
    p.counts = [p.slot(f'subjects.hubs.{i}.liveCount') for i in range(len(p.tiles))]
    return p


def overlay(tmp, real, changes):
    """A Lessons tree at tmp/L: symlinks to the real checkout, with `changes` {relative path: bytes or None} applied.
    Only the directories on a changed path are materialised; the real checkout is never written."""
    root = Path(tmp) / 'L'
    root.mkdir()
    for entry in Path(real).iterdir():
        os.symlink(entry, root / entry.name)
    for rel, data in changes.items():
        parts, cur, src = Path(rel).parts, root, Path(real)
        for part in parts[:-1]:
            cur, src = cur / part, src / part
            if cur.is_symlink():
                cur.unlink()
                cur.mkdir()
                for entry in src.iterdir():
                    os.symlink(entry, cur / entry.name)
            elif not cur.exists():
                cur.mkdir()
        target = cur / parts[-1]
        if target.is_symlink() or target.exists():
            target.unlink()
        if data is not None:
            target.write_bytes(data)
    return root


def refused(call, *args):
    try:
        call(*args)
    except ValueError as refusal:
        return str(refusal)
    return None


def j93_self_test(root, lessons_root, tmp):
    """The J93 replacements: door cards, subject tiles and flagship cards follow their records."""
    import shared_navigation
    results = {}
    record_path = root / 'data/audience-homepages.json'
    record = json.loads(record_path.read_text())
    rec = record['audiences']
    expected_doors = [rec[k]['route'] for k in DOOR_KEYS]
    real = parse_home(render_home(record_path, lessons_root))
    real_page = render_home(record_path, lessons_root)
    # Doors (replaces the planted audience row): four cards, the record's routes and labels, by key.
    assert real.doors == expected_doors, ('door routes are not the record routes in key order', real.doors)
    assert real.door_labels == [rec[k]['label'] for k in DOOR_KEYS], 'door labels are not the record labels'
    planted = json.loads(json.dumps(record))
    planted['audiences']['parents'] = {**planted['audiences']['parents'], 'route': '/for/planted-ux2/', 'label': 'Planted UX2 audience'}
    (tmp / 'door-plant.json').write_text(json.dumps(planted))
    with_plant = parse_home(render_home(tmp / 'door-plant.json', lessons_root))
    assert with_plant.doors[2] == '/for/planted-ux2/' and with_plant.door_labels[2] == 'Planted UX2 audience', 'planted door route did not appear on its door card'
    assert with_plant.doors[:2] + with_plant.doors[3:] == expected_doors[:2] + expected_doors[3:], 'a planted door moved another door'
    extra = json.loads(json.dumps(record))
    extra['audiences']['planted'] = {**extra['audiences']['partners'], 'route': '/for/planted-extra-ux2/', 'label': 'Planted extra audience'}
    (tmp / 'extra-plant.json').write_text(json.dumps(extra))
    extra_page = render_home(tmp / 'extra-plant.json', lessons_root)
    assert parse_home(extra_page).doors == expected_doors and 'planted-extra-ux2' not in extra_page, 'an extra record key must not become a door (doors are four, by key)'
    missing = json.loads(json.dumps(record))
    del missing['audiences']['schools']
    (tmp / 'missing-door.json').write_text(json.dumps(missing))
    assert refused(render_home, tmp / 'missing-door.json', lessons_root), 'a record without a door key must be refused'
    assert 'planted-ux2' not in real_page and 'Planted UX2' not in real_page, 'the real record must not carry the plant'
    results['doors'] = len(real.doors)
    # Subject tiles (replaces the featured-subject checks): the four fixed groups, the hub's own counts.
    slugs = [slug for slug, *_ in bp.SUBJECT_CARDS]
    assert real.tiles == ['/Lessons/subject.html?subject=' + s for s in slugs], 'homepage tiles are not the four fixed subject groups'
    hub = home_slots.hub_view(lessons_root, slugs)
    assert real.counts == [str(hub['counts'][s]) for s in slugs], 'tile counts are not the hub distinctLessons'
    rows = json.loads((Path(lessons_root) / 'resources.json').read_text())
    plant_rows = rows + [{'subject': 'Planted Subject', 'title': 'A', 'file': 'a.html', 'type': 'lesson'},
                         {'subject': 'Science', 'title': 'Planted game', 'file': 'planted-game.html', 'type': 'game'}]
    with tempfile.TemporaryDirectory() as t:
        L = overlay(t, lessons_root, {'resources.json': json.dumps(plant_rows).encode()})
        page = render_home(record_path, L)
        tiles = parse_home(page)
        assert 'subject=x-planted-subject' not in page and tiles.tiles == real.tiles, 'homepage must keep its four featured subjects'
        assert tiles.counts == real.counts and 'planted-game' not in page, 'a game row must never become a tile or a counted lesson'
    with tempfile.TemporaryDirectory() as t:
        L = overlay(t, lessons_root, {'resources.json': json.dumps([r for r in rows if bp.card_of(r) != 'art-studio']).encode()})
        assert refused(render_home, record_path, L), 'an empty fixed subject group must be refused, never published as a tile'
    # The full catalogue (replaces "View all" -> /Lessons/): the Resources card is always present at the HUB_LINKS route.
    resources = dict((label, route) for route, label in shared_navigation.HUB_LINKS)['Resources']
    assert real.tools[0] == resources and with_plant.tools[0] == resources, 'the Resources card must stay one tap away'
    results['tiles'] = len(real.tiles)
    # Flagship cards (replaces the preview / Try-a-lesson binding): registry rows, lesson file and folder.
    assert [c['key'] for c in real.cards] == list(home_slots.PATHWAYS) and [c['badges'] for c in real.cards] == [9, 9, 9], [c['badges'] for c in real.cards]
    files = [unquote(c['lesson'][len('/Lessons/'):]) for c in real.cards]
    by_file = {r.get('file'): r for r in rows}
    for card, f in zip(real.cards, files):
        assert f in by_file and card['outcome'] == ' '.join(str(by_file[f]['desc']).split()), 'flagship outcome is not the registry row'
    hub_route = '/Lessons/subject.html?subject=' + home_slots.FLAGSHIP[0]
    with tempfile.TemporaryDirectory() as t:  # vb-3 (a): the lesson page leaves the tree -> the badge links the subject hub
        L = overlay(t, lessons_root, {files[0]: None})
        gone = parse_home(render_home(record_path, L))
        assert gone.cards[0]['lesson'] == hub_route and gone.cards[1]['lesson'] == real.cards[1]['lesson'], 'a missing lesson must link its subject hub'
    folder, code = files[1].rsplit('/', 1)[0], files[1].rsplit('/', 1)[1].rsplit('.', 1)[0]
    with tempfile.TemporaryDirectory() as t:  # uz-6 (d): badges follow the lesson folder; images never become badges
        L = overlay(t, lessons_root, {folder + '/' + code + '_Planted_member.docx': b'x', folder + '/planted.png': b'x'})
        grown = parse_home(render_home(record_path, L))
        assert grown.cards[1]['badges'] == 10 and ('DOCX', 'Planted member') in grown.cards[1]['members'], 'a new pack member must become a badge'
        assert [m[1] for m in grown.cards[1]['members']] == [m[1] for m in sorted(grown.cards[1]['members'], key=lambda m: code + '_' + m[1].replace(' ', '_') + '.' + m[0].lower())], 'badges must stay in file-name order'
        assert grown.cards[0]['badges'] == 9 and grown.cards[2]['badges'] == 9, 'other cards must not move'
    changed = [dict(r) for r in rows]
    for r in changed:
        if r.get('file') == files[0]:
            r['desc'] = str(r['desc']) + ' Planted outcome.'
    with tempfile.TemporaryDirectory() as t:  # the outcome is the registry row's, not typed
        L = overlay(t, lessons_root, {'resources.json': json.dumps(changed).encode()})
        assert parse_home(render_home(record_path, L)).cards[0]['outcome'].endswith('Planted outcome.'), 'the flagship outcome must follow its registry row'
    with tempfile.TemporaryDirectory() as t:  # a pathway row leaves the registry -> spec fallback or refusal, never a half strip
        L = overlay(t, lessons_root, {'resources.json': json.dumps([r for r in rows if r.get('file') != files[1]]).encode()})
        why = refused(render_home, record_path, L)
        if why is None:
            fallback = parse_home(render_home(record_path, L))
            assert [c['key'] for c in fallback.cards] == list(home_slots.PATHWAYS) and fallback.cards[1]['lesson'] != real.cards[1]['lesson'], 'fallback must bind a full strip'
        results['flagshipRowRemoved'] = 'refused' if why else 'fallback bound'
    assert render_home(record_path, lessons_root) == real_page, 'the real page must be unchanged after the plants'
    results['flagshipBadges'] = [c['badges'] for c in real.cards]
    results['counts'] = [int(c) for c in real.counts]
    return results


