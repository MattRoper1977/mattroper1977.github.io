async function reducedMotionProbe(browser, origin, route) {
  const context = await newContext(browser, { reduced: true });
  await context.addInitScript(() => {
    window.__mbmReducedProbe = {
      attached: false,
      attachedAt: null,
      clearedAt: null,
      detachedAt: null,
      started: false,
      endElapsed: null,
      endAt: null,
    };
    document.addEventListener('animationstart', event => {
      if (event.animationName !== 'mbmSplash' || !event.target?.matches?.('[data-mbm-maker-splash]')) return;
      window.__mbmReducedProbe.started = true;
    }, true);
    document.addEventListener('animationend', event => {
      if (event.animationName !== 'mbmSplash' || !event.target?.matches?.('[data-mbm-maker-splash]')) return;
      window.__mbmReducedProbe.endElapsed = event.elapsedTime * 1000;
      window.__mbmReducedProbe.endAt = performance.now();
    }, true);
    new MutationObserver(records => {
      const probe = window.__mbmReducedProbe;
      const recordClearance = el => {
        if (!el || !probe.attached || probe.clearedAt !== null) return;
        const css = getComputedStyle(el);
        if (el.getAttribute('aria-hidden') === 'true' || el.inert || css.visibility === 'hidden' || css.pointerEvents === 'none') {
          probe.clearedAt = performance.now();
        }
      };
      for (const record of records) {
        if (record.type === 'attributes' && record.target.matches?.('[data-mbm-maker-splash]')) recordClearance(record.target);
        for (const node of record.addedNodes) {
          const el = node.nodeType === 1 && node.matches?.('[data-mbm-maker-splash]') ? node : node.querySelector?.('[data-mbm-maker-splash]');
          if (!el || probe.attached) continue;
          probe.attached = true;
          probe.attachedAt = performance.now();
          recordClearance(el);
        }
        for (const node of record.removedNodes) {
          const removed = node.nodeType === 1 && node.matches?.('[data-mbm-maker-splash]') ? node : node.querySelector?.('[data-mbm-maker-splash]');
          if (!removed || !probe.attached || probe.detachedAt !== null) continue;
          probe.detachedAt = performance.now();
          if (probe.clearedAt === null) probe.clearedAt = probe.detachedAt;
        }
      }
    }).observe(document, { childList: true, subtree: true, attributes: true, attributeFilter: ['class', 'style', 'aria-hidden', 'inert'] });
  });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(`pageerror: ${error.message}`));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(`console: ${msg.text()}`); });
  const wall = Date.now();
  await page.goto(origin + encodeURI(splashProbeRoute(route)), { waitUntil: 'commit', timeout: 30000 });
  await page.waitForTimeout(850);
  const probe = await page.evaluate(() => window.__mbmReducedProbe);
  const final = await page.locator('[data-mbm-maker-splash]').evaluate(el => { const css = getComputedStyle(el); return { visibility: css.visibility, pointerEvents: css.pointerEvents }; }).catch(() => ({ visibility: 'detached', pointerEvents: 'none' }));
  await page.waitForLoadState('domcontentloaded', { timeout: 30000 }).catch(error => errors.push(`domcontentloaded: ${error.message}`));
  const local = await page.evaluate(key => { try { return localStorage.getItem(key); } catch { return null; } }, KEY);
  await context.close();
  return { wall, local, errors, probe, final };
}

function reducedMotionClearanceElapsed(result) {
  const attachedAt = result.probe?.attachedAt;
  const clearedAt = result.probe?.clearedAt;
  return Number.isFinite(attachedAt) && Number.isFinite(clearedAt) ? clearedAt - attachedAt : null;
}

function reducedMotionObservedElapsed(result) {
  return Number.isFinite(result.probe?.endElapsed) ? result.probe.endElapsed : reducedMotionClearanceElapsed(result);
}

function reducedMotionClearsWithinDeadline(result) {
  const elapsed = reducedMotionObservedElapsed(result);
  return result.probe?.attached === true && elapsed >= 300 && elapsed <= 500 && result.final.pointerEvents === 'none';
}

async function opacityTraceProbe(browser, origin, route, { seed } = {}) {
  const context = await newContext(browser, { viewport: VIEWPORTS[0], seed });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(`pageerror: ${error.message}`));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(`console: ${msg.text()}`); });
  await page.addInitScript(() => {
    window.__q1Trace = { samples: [], firstSeenAt: null, attachedAt: null, exposedFrames: 0, done: false };
    new MutationObserver(records => {
      for (const record of records) for (const node of record.addedNodes) {
        const el = node.nodeType === 1 && (node.id === 'mbmSplash' ? node : node.querySelector?.('#mbmSplash'));
        if (el && window.__q1Trace.attachedAt === null) window.__q1Trace.attachedAt = performance.now();
      }
    }).observe(document, { childList: true, subtree: true });
    function tick() {
      const t = window.__q1Trace;
      const el = document.getElementById('mbmSplash');
      const now = performance.now();
      if (el) {
        if (t.firstSeenAt === null) t.firstSeenAt = now;
        const elapsed = now - t.firstSeenAt;
        if (elapsed <= 300) {
          const cs = getComputedStyle(el);
          t.samples.push({ t: Math.round(elapsed), opacity: Number(cs.opacity), visibility: cs.visibility });
        } else {
          t.done = true;
          return;
        }
      } else if (t.firstSeenAt === null && document.body && document.body.children.length > 0) {
        t.exposedFrames += 1;
      } else if (t.firstSeenAt !== null) {
        const elapsed = now - t.firstSeenAt;
        if (elapsed <= 300) t.samples.push({ t: Math.round(elapsed), opacity: 0, visibility: 'detached' });
        else { t.done = true; return; }
      }
      if (t.firstSeenAt === null && now > 2000) { t.done = true; return; }
      requestAnimationFrame(tick);
    }
    requestAnimationFrame(tick);
  });
  await page.goto(origin + encodeURI(splashProbeRoute(route)), { waitUntil: 'commit', timeout: 30000 });
  await page.waitForFunction(() => window.__q1Trace?.done === true, null, { polling: 50, timeout: 6000 }).catch(() => {});
  const trace = await page.evaluate(() => window.__q1Trace).catch(() => null);
  await context.close();
  return { trace, errors };
}

async function ownScreenProbe(browser, origin, route, selector, viewport) {
  const context = await newContext(browser, { viewport });
  const page = await context.newPage();
  const pageErrors = [], consoleErrors = [];
  page.on('pageerror', error => pageErrors.push(error.message || String(error)));
  page.on('console', msg => { if (msg.type() === 'error') consoleErrors.push(msg.text()); });
  await page.addInitScript(ownSelector => {
    const p = window.__ownScreenProbe = {
      genericEnteredDom: false,
      genericEverPresent: false,
      genericCount: 0,
      ownSeen: false,
      ownHasBrand: false,
      ownFirstAt: null,
      ownRect: null,
      ownText: '',
    };
    function hasGeneric(node) {
      if (!node || node.nodeType !== 1) return false;
      if (node.id === 'mbmSplash' || node.matches?.('[data-mbm-maker-splash]')) return true;
      return !!node.querySelector?.('#mbmSplash,[data-mbm-maker-splash]');
    }
    function checkOwn() {
      const own = document.querySelector(ownSelector);
      if (!own) return;
      const css = getComputedStyle(own);
      const rect = own.getBoundingClientRect();
      const label = `${own.getAttribute('aria-label') || ''} ${own.textContent || ''}`.replace(/\s+/g, ' ').trim();
      const branded = /made\s*by\s*matt|madebymatt/i.test(label);
      const visible = css.display !== 'none' && css.visibility !== 'hidden' && Number(css.opacity) > 0 && rect.width > 0 && rect.height > 0;
      if (visible && branded) {
        p.ownSeen = true;
        p.ownHasBrand = true;
        if (p.ownFirstAt === null) p.ownFirstAt = Math.round(performance.now());
        if (!p.ownRect) p.ownRect = { width: Math.round(rect.width), height: Math.round(rect.height) };
        if (!p.ownText) p.ownText = label.slice(0, 120);
      }
    }
    new MutationObserver(records => {
      for (const record of records) {
        for (const node of record.addedNodes) {
          if (hasGeneric(node)) {
            p.genericEnteredDom = true;
            p.genericCount += 1;
          }
        }
      }
      checkOwn();
    }).observe(document, { childList: true, subtree: true });
    function sample() {
      if (document.querySelector('#mbmSplash,[data-mbm-maker-splash]')) {
        p.genericEnteredDom = true;
        p.genericEverPresent = true;
      }
      checkOwn();
      requestAnimationFrame(sample);
    }
    requestAnimationFrame(sample);
  }, selector);
  let status = null;
  try {
    const response = await page.goto(origin + encodeURI(splashProbeRoute(route)), { waitUntil: 'load', timeout: 60000 });
    status = response?.status() ?? null;
  } catch (error) {
    pageErrors.push(`navigation: ${error.message || String(error)}`);
  }
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)))).catch(() => {});
  await page.waitForTimeout(250);
  const snapshot = await page.evaluate(() => ({
    probe: window.__ownScreenProbe || null,
    genericPresentAtEnd: !!document.querySelector('#mbmSplash,[data-mbm-maker-splash]'),
  })).catch(error => ({ probe: null, genericPresentAtEnd: false, evalError: error.message }));
  await context.close();
  return { route, selector, viewport, status, ...snapshot, pageErrors, consoleErrors };
}

