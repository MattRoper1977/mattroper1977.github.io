/* CyberPulse's CP4c gate proves renderer=2d reaches its authored Canvas
 * fallback. This verifier judges the generated splash, focus handoff and way
 * out, not renderer fidelity, so every CyberPulse probe uses that proved hatch
 * instead of spending the CI budget in software WebGL. */
function splashProbeRoute(route) {
  if (!/^\/cyberpulse\/(?:[?#]|$)/.test(route) || /(?:[?&])renderer=/.test(route)) return route;
  const hashAt = route.indexOf('#');
  const base = hashAt < 0 ? route : route.slice(0, hashAt);
  const hash = hashAt < 0 ? '' : route.slice(hashAt);
  return `${base}${base.includes('?') ? '&' : '?'}renderer=2d${hash}`;
}
const BEGIN = '<!-- MBM-MAKER-SPLASH:BEGIN generated by tools/render_maker_splash.py, do not edit by hand -->';
const END = '<!-- MBM-MAKER-SPLASH:END -->';
const REGION = new RegExp('(?:\\r?\\n)?' + escapeRegex(BEGIN) + '[\\s\\S]*?' + escapeRegex(END) + '(?:\\r?\\n)?');
const VIEWPORTS = [{ width: 390, height: 844 }, { width: 1280, height: 800 }];
