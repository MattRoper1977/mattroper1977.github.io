function splashProbeRoute(route) {
  if (!/^\/cyberpulse\/(?:[?#]|$)/.test(route) || /(?:[?&])renderer=/.test(route)) return route;
  const hashAt = route.indexOf('#');
  const base = hashAt < 0 ? route : route.slice(0, hashAt);
  const hash = hashAt < 0 ? '' : route.slice(hashAt);
  return `${base}${base.includes('?') ? '&' : '?'}renderer=2d${hash}`;
}
