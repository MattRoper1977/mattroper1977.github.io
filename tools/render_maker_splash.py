#!/usr/bin/env python3
"""Render the estate-wide Made by Matt splash from one declared implementation.

The routes are declared in data/hud-coverage.json under ``makerSplash``.  This
tool is the only writer of the MBM-MAKER-SPLASH region.  It deliberately keeps
the region byte-identical across every route: title, slug and focus target are
derived at runtime, while the visual donor is the CyberPulse ``Made by / Matt /
presents`` mark measured for the 2026-08-27 splash-canon release.

Usage:
  python3 tools/render_maker_splash.py --root . --check
  python3 tools/render_maker_splash.py --root . --write

Multiple ``--root`` arguments are accepted for an assembled local proof, but
each checkout reads and owns only its own ledger.
"""

