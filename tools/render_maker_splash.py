def build_region() -> str:
    return f"{BEGIN}\n<script>{JS}</script>\n{END}\n"


@dataclass(frozen=True)
class Entry:
    route: str
    reason: str = ""


def entries(data: dict, key: str) -> list[Entry]:
    raw = data.get(key)
    if not isinstance(raw, list):
        raise ValueError(f"makerSplash.{key} is missing or is not a list")
    out: list[Entry] = []
    for item in raw:
        if isinstance(item, str):
            route, reason = item, ""
        elif isinstance(item, dict) and isinstance(item.get("route"), str):
            route, reason = item["route"], str(item.get("reason", ""))
        else:
            raise ValueError(f"makerSplash.{key} contains an invalid entry: {item!r}")
        if key != "applied" and not reason:
            raise ValueError(f"makerSplash.{key} entry {route!r} has no reason")
        out.append(Entry(route, reason))
    return out


def ledger(root: Path) -> tuple[list[Entry], list[Entry], list[Entry]]:
    path = root / "data" / "hud-coverage.json"
    if not path.is_file():
        raise ValueError(f"{path}: missing route ledger")
    data = json.loads(path.read_text(encoding="utf-8"))
    section = data.get("makerSplash")
    if not isinstance(section, dict):
        raise ValueError(f"{path}: makerSplash target section is missing")
    applied = entries(section, "applied")
    declined = entries(section, "declined-with-reason")
    variants = entries(section, "variant-retained-with-reason")
    all_routes = [e.route for group in (applied, declined, variants) for e in group]
    dupes = sorted({route for route in all_routes if all_routes.count(route) > 1})
    if dupes:
        raise ValueError(f"{path}: routes appear in more than one makerSplash class: {dupes}")
    if not all_routes:
        raise ValueError(f"{path}: makerSplash target lists are all empty")
    return applied, declined, variants


def route_path(root: Path, route: str, *, require_html: bool = True) -> Path:
    if not route.startswith("/") or route.startswith("//"):
        raise ValueError(f"invalid local route {route!r}")
    rel = route[len("/Lessons/") :] if route.startswith("/Lessons/") else route.lstrip("/")
    path = root / rel
    if route.endswith("/"):
        path = path / "index.html"
    if require_html and path.suffix.lower() != ".html":
        raise ValueError(f"{route}: maker splash targets must resolve to HTML")
    resolved_root = root.resolve()
    resolved = path.resolve()
    if resolved != resolved_root and resolved_root not in resolved.parents:
        raise ValueError(f"{route}: target escapes {root}")
    if not path.is_file():
        raise ValueError(f"{route}: no file at {path}")
    return path


def remove_balanced_splash(html: str) -> tuple[str, int]:
    """Remove legacy literal #mbmSplash markup, leaving unrelated UI intact."""
    count = 0
    start_re = re.compile(r"<(div|section)\b[^>]*\bid\s*=\s*(['\"])mbmSplash\2[^>]*>", re.IGNORECASE)
    while True:
        match = start_re.search(html)
        if not match:
            return html, count
        tag = match.group(1).lower()
        token_re = re.compile(rf"</?{tag}\b[^>]*>", re.IGNORECASE)
        depth = 0
        end = None
        for token in token_re.finditer(html, match.start()):
            depth += -1 if token.group(0).startswith("</") else 1
            if depth == 0:
                end = token.end()
                break
        if end is None:
            raise ValueError("legacy #mbmSplash markup is unbalanced")
        html = html[: match.start()] + html[end:]
        count += 1


def strip_legacy(html: str) -> tuple[str, list[str]]:
    notes: list[str] = []
    for pattern in LEGACY_REGIONS:
        html, n = pattern.subn("", html)
        if n:
            notes.append(f"legacy-marker-region:{n}")
    html, n = remove_balanced_splash(html)
    if n:
        notes.append(f"legacy-static-markup:{n}")
    # CyberPulse's original handlers live inside its main script rather than
    # beside the markup.  Removing the exact ownership block prevents a null
    # legacy reference after the generated block takes over.
    html, n = re.subn(
        r"\s*let splashActive=true;const makerSplash=\$\('mbmSplash'\);.*?setTimeout\(\(\)=>dismissSplash\(false\),reducedMotion\?350:2100\);",
        "",
        html,
        flags=re.DOTALL,
    )
    if n:
        notes.append(f"legacy-cyberpulse-handlers:{n}")
    # Apex Golf calls a page-local legacy dismiss function from boot even when
    # the literal overlay has been removed.  A no-op preserves that call site;
    # the maker block now owns dismissal.
    html, n = re.subn(
        r"function dismissSplash\(\)\{.*?\}\s*function boot\(",
        "function dismissSplash(){}\nfunction boot(",
        html,
        count=1,
        flags=re.DOTALL,
    )
    if n:
        notes.append("legacy-apexgolf-handler:1")
    # Remove an immediately adjacent legacy bootstrap when its only reason to
    # exist was the deleted literal markup.  Bounded length avoids touching a
    # game's main script.
    html, n = re.subn(
        r"(<body\b[^>]*>\s*)(?:<noscript\b[\s\S]{0,1600}?</noscript>\s*)?<script\b[^>]*>[\s\S]{0,1800}?getElementById\(['\"]mbmSplash['\"]\)[\s\S]{0,1800}?</script>\s*",
        r"\1",
        html,
        count=1,
        flags=re.IGNORECASE,
    )
    if n:
        notes.append("legacy-adjacent-bootstrap:1")
    return html, notes


def insert_point(html: str) -> int:
    """After <body>, with the inline-exit trailing-comment walk as fallback.

    The early point is load-bearing: the storage decision must happen before a
    first paint, otherwise a suppressed route flashes an overlay.  Malformed
    legacy shells without an opening body retain the estate's established
    walk-back before trailing sentinels and ``</body>``.
    """
    body = re.search(r"<body\b[^>]*>", html, re.IGNORECASE)
    if body:
        return body.end()
    idx = html.lower().rfind("</body>")
    if idx < 0:
        raise ValueError("no <body> insertion point")
    head = html[:idx]
    while True:
        stripped = head.rstrip()
        if not stripped.endswith("-->"):
            break
        start = stripped.rfind("<!--")
        if start < 0:
            break
        head, idx = stripped[:start], start
    return idx


def expected_html(source: str, region: str) -> tuple[str, list[str]]:
    base = REGION_RE.sub("", source, count=1)
    base, notes = strip_legacy(base)
    at = insert_point(base)
    return base[:at] + "\n" + region + base[at:], notes


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", action="append", required=True)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()

    region = build_region()
    digest = hashlib.sha256(region.encode("utf-8")).hexdigest()
    print(f"region: {len(region.encode('utf-8'))} bytes, sha256 {digest}")
    bad = changed = total = 0
    for raw_root in args.root:
        root = Path(raw_root).resolve()
        try:
            applied, declined, variants = ledger(root)
        except (OSError, ValueError, json.JSONDecodeError) as exc:
            print(f"ERROR {exc}", file=sys.stderr)
            return 2
        for entry in declined:
            try:
                path = route_path(root, entry.route, require_html=False)
            except ValueError as exc:
                print(f"ERROR {exc}", file=sys.stderr)
                return 2
            has_region = path.suffix.lower() == ".html" and bool(
                REGION_RE.search(path.read_text(encoding="utf-8"))
            )
            if has_region and args.write:
                source = path.read_text(encoding="utf-8")
                path.write_text(REGION_RE.sub("", source, count=1), encoding="utf-8")
                has_region = False
                changed += 1
                status = "reverted"
            else:
                status = "drift" if has_region else "declined"
            print(f"  {status:9} {entry.route}  {path.stat().st_size} B")
            if has_region:
                bad += 1
        for entry in variants:
            try:
                path = route_path(root, entry.route)
            except ValueError as exc:
                print(f"ERROR {exc}", file=sys.stderr)
                return 2
            has_region = bool(REGION_RE.search(path.read_text(encoding="utf-8")))
            status = "drift" if has_region else "variant"
            print(f"  {status:9} {entry.route}  {path.stat().st_size} B")
            if has_region:
                bad += 1
        for entry in applied:
            total += 1
            try:
                path = route_path(root, entry.route)
                source = path.read_text(encoding="utf-8")
                expected, notes = expected_html(source, region)
            except (OSError, ValueError) as exc:
                print(f"ERROR {exc}", file=sys.stderr)
                return 2
            if source == expected:
                status = "ok"
            elif args.check:
                status = "missing" if not REGION_RE.search(source) else "drift"
                bad += 1
            else:
                before = len(source.encode("utf-8"))
                path.write_text(expected, encoding="utf-8")
                after = path.stat().st_size
                status = "stamped"
                changed += 1
                print(f"    bytes {before} -> {after}; migrations {','.join(notes) if notes else 'none'}")
            print(f"  {status:9} {entry.route}  {path.stat().st_size} B  {path.relative_to(root)}")
    if total == 0:
        print("ERROR makerSplash.applied is empty across all roots", file=sys.stderr)
        return 2
    print(f"{total} applied target(s); {changed} written; {bad} divergent")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
